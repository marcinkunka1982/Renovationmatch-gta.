"""RenovationMatch GTA API backed by PostgreSQL.

Requires DATABASE_URL and psycopg 3. Review security and privacy before public launch.
"""
import json
import os
import re
import secrets
import threading
from datetime import datetime, timezone
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler
from pathlib import Path
from urllib.parse import urlparse

import psycopg
from psycopg.rows import dict_row
from security import allowed, notify

ROOT = Path(__file__).resolve().parent
TOKEN = os.getenv('RM_ADMIN_TOKEN', '')
DATABASE_URL = os.getenv('DATABASE_URL', '')


def connect():
    if not DATABASE_URL:
        raise RuntimeError('DATABASE_URL is required')
    return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=15)


def init():
    with connect() as db:
        db.execute('''CREATE TABLE IF NOT EXISTS leads (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            project_type TEXT NOT NULL, city TEXT NOT NULL,
            budget TEXT, timing TEXT, details TEXT NOT NULL,
            name TEXT NOT NULL, email TEXT NOT NULL, phone TEXT NOT NULL,
            consent INTEGER NOT NULL, created_at TEXT NOT NULL,
            assigned_contractor BIGINT, status TEXT NOT NULL DEFAULT 'new'
        )''')
        db.execute('''CREATE TABLE IF NOT EXISTS audit (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            event TEXT NOT NULL, subject_id BIGINT, created_at TEXT NOT NULL
        )''')
        db.execute('''CREATE TABLE IF NOT EXISTS contractors (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            business TEXT NOT NULL, contact TEXT NOT NULL, email TEXT NOT NULL,
            phone TEXT NOT NULL, services TEXT NOT NULL, cities TEXT NOT NULL,
            created_at TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending'
        )''')
        db.execute('CREATE INDEX IF NOT EXISTS ix_lead_status ON leads(status)')


def clean(value, limit=500):
    return str(value or '').strip()[:limit]


def valid_email(value):
    return bool(re.fullmatch(r'[^\s@]+@[^\s@]+\.[^\s@]+', value))


class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def send_json(self, code, obj):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header('Content-Type', 'application/json; charset=utf-8')
        self.send_header('Content-Length', str(len(body)))
        self.send_header('Cache-Control', 'no-store')
        self.send_header('X-Content-Type-Options', 'nosniff')
        self.end_headers()
        self.wfile.write(body)

    def end_headers(self):
        self.send_header('X-Frame-Options', 'DENY')
        self.send_header('Referrer-Policy', 'no-referrer')
        self.send_header('Content-Security-Policy', "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; connect-src 'self'; object-src 'none'; base-uri 'none'")
        super().end_headers()

    def admin(self):
        return bool(TOKEN) and secrets.compare_digest(self.headers.get('X-Admin-Token', ''), TOKEN)

    def do_GET(self):
        path = urlparse(self.path).path
        if (path in ('/server.py', '/security.py', '/README.md', '/requirements.txt', '/render.yaml')
                or path.startswith('/.')
                or path.endswith(('.sqlite3', '.sqlite3-wal', '.sqlite3-shm', '.db', '.pyc', '.py', '.yaml'))):
            return self.send_json(404, {'error': 'Not found'})
        if path == '/api/health':
            return self.send_json(200, {'ok': True, 'mode': 'postgresql'})
        if path == '/api/admin/leads':
            if not self.admin():
                return self.send_json(403, {'error': 'Admin token required'})
            with connect() as db:
                rows = db.execute('SELECT * FROM leads ORDER BY id DESC').fetchall()
            return self.send_json(200, {'leads': rows})
        if path == '/api/admin/contractors':
            if not self.admin():
                return self.send_json(403, {'error': 'Admin token required'})
            with connect() as db:
                rows = db.execute('SELECT * FROM contractors ORDER BY id DESC').fetchall()
            return self.send_json(200, {'contractors': rows})
        if path.startswith('/api/'):
            return self.send_json(404, {'error': 'Not found'})
        return super().do_GET()

    def do_POST(self):
        path = urlparse(self.path).path
        try:
            n = int(self.headers.get('Content-Length', '0'))
            if n <= 0 or n > 16000:
                return self.send_json(413, {'error': 'Invalid request size'})
            data = json.loads(self.rfile.read(n))
            if not isinstance(data, dict):
                raise ValueError()
        except (ValueError, TypeError, json.JSONDecodeError):
            return self.send_json(400, {'error': 'Invalid JSON'})

        now = datetime.now(timezone.utc).isoformat()
        if path in ('/api/leads', '/api/contractors') and not allowed((path, self.client_address[0])):
            return self.send_json(429, {'error': 'Too many requests; please try later'})

        if path == '/api/leads':
            fields = {k: clean(data.get(k), 2000 if k == 'details' else 150)
                      for k in ('project_type', 'city', 'budget', 'timing', 'details', 'name', 'email', 'phone')}
            if (any(not fields[k] for k in ('project_type', 'city', 'details', 'name', 'email', 'phone'))
                    or not valid_email(fields['email'])
                    or len(re.sub(r'\D', '', fields['phone'])) < 10
                    or data.get('consent') is not True):
                return self.send_json(400, {'error': 'Please complete required fields and consent'})
            with connect() as db:
                lead_id = db.execute('''INSERT INTO leads
                    (project_type,city,budget,timing,details,name,email,phone,consent,created_at)
                    VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id''',
                    (*fields.values(), 1, now)).fetchone()['id']
                db.execute('INSERT INTO audit(event,subject_id,created_at) VALUES (%s,%s,%s)',
                           ('lead_created', lead_id, now))
            threading.Thread(target=self._notify,
                             args=('New renovation request', f'Lead #{lead_id} received. Open your admin dashboard to review.'),
                             daemon=True).start()
            return self.send_json(201, {'ok': True, 'request_id': lead_id})

        if path == '/api/contractors':
            fields = {k: clean(data.get(k), 500)
                      for k in ('business', 'contact', 'email', 'phone', 'services', 'cities')}
            if any(not v for v in fields.values()) or not valid_email(fields['email']):
                return self.send_json(400, {'error': 'All contractor fields are required'})
            with connect() as db:
                contractor_id = db.execute('''INSERT INTO contractors
                    (business,contact,email,phone,services,cities,created_at)
                    VALUES (%s,%s,%s,%s,%s,%s,%s) RETURNING id''',
                    (*fields.values(), now)).fetchone()['id']
            threading.Thread(target=self._notify,
                             args=('New contractor application', f'Contractor #{contractor_id} registered. Review in admin dashboard.'),
                             daemon=True).start()
            return self.send_json(201, {'ok': True, 'contractor_id': contractor_id})

        if path == '/api/admin/assign':
            if not self.admin():
                return self.send_json(403, {'error': 'Admin token required'})
            try:
                lead_id = int(data['lead_id'])
                contractor_id = int(data['contractor_id'])
            except (ValueError, TypeError, KeyError):
                return self.send_json(400, {'error': 'Invalid IDs'})
            with connect() as db:
                if not db.execute('SELECT 1 FROM contractors WHERE id=%s', (contractor_id,)).fetchone():
                    return self.send_json(404, {'error': 'Contractor not found'})
                row = db.execute('''UPDATE leads SET assigned_contractor=%s,status='assigned'
                    WHERE id=%s AND assigned_contractor IS NULL AND status='new'
                    RETURNING id''', (contractor_id, lead_id)).fetchone()
                if not row:
                    return self.send_json(409, {'error': 'Lead not found or already assigned'})
                db.execute('INSERT INTO audit(event,subject_id,created_at) VALUES (%s,%s,%s)',
                           ('lead_assigned', lead_id, now))
            return self.send_json(200, {'ok': True})
        return self.send_json(404, {'error': 'Not found'})

    @staticmethod
    def _notify(subject, message):
        try:
            notify(subject, message)
        except Exception as exc:
            print('Notification delivery failed:', type(exc).__name__)


if __name__ == '__main__':
    init()
    port = int(os.getenv('PORT', '8000'))
    print(f'RenovationMatch GTA listening on port {port}')
    ThreadingHTTPServer((os.getenv('RM_HOST', '127.0.0.1'), port), Handler).serve_forever()
